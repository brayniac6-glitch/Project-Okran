#!/usr/bin/env python3
"""Generate a Rust enum from sheet enum rows, so code stays a projection of the sheet.

  python tools/gen_enum.py <tid> <RustName> <out.rs> [doc line]

Variant names are the sheet names in CamelCase; each row's value is the discriminant. The
generated file includes a test that re-reads sheet/enums.tsv and fails if they diverge.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def camel(n):
    parts = [p for p in n.strip("_").split("_") if p]
    s = "".join(p[:1].upper() + p[1:].lower() for p in parts)
    if not s or s[0].isdigit():
        s = "V" + s
    return s


def main():
    tid, rust, out = sys.argv[1], sys.argv[2], Path(sys.argv[3])
    doc = sys.argv[4] if len(sys.argv) > 4 else ""
    rows = []
    for line in (ROOT / "sheet" / "enums.tsv").read_text(encoding="utf-8").splitlines():
        f = line.split("\t")
        if f[0] == tid:
            rows.append((f[1], int(f[2], 0)))
    seen = {}
    variants = []
    for name, v in rows:
        c = camel(name)
        if c in seen:
            c = f"{c}{v}"
        seen[c] = v
        variants.append((c, name, v))
    t = "\\t"
    lines = [
        f"//! {doc}" if doc else f"//! {rust} (sheet {tid}).",
        "//!",
        f"//! Generated by `python tools/gen_enum.py {tid} {rust} ...` from sheet/enums.tsv; do not edit.",
        "",
        f"/// @type {rust if tid != 'T00007' else 'ItemType'}",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]",
        "#[repr(i32)]",
        f"pub enum {rust} {{",
    ]
    lines += [f"    {c} = {v}," for c, _, v in variants]
    lines += ["}", "", f"impl {rust} {{", "    pub fn from_i32(v: i32) -> Option<Self> {", "        Some(match v {"]
    lines += [f"            {v} => Self::{c}," for c, _, v in variants]
    lines += ["            _ => return None,", "        })", "    }", "", "    /// The name as in the sheet (the FCS schema name).",
              "    pub fn name(self) -> &'static str {", "        match self {"]
    lines += [f'            Self::{c} => "{n}",' for c, n, _ in variants]
    lines += ["        }", "    }", "}", "", "#[cfg(test)]", "mod tests {", "    use super::*;", "", "    #[test]",
              "    fn matches_sheet() {", '        let sheet = include_str!("../../sheet/enums.tsv");', "        let mut n = 0;",
              f'        for line in sheet.lines().filter(|l| l.starts_with("{tid}{t}")) {{',
              f"            let f: Vec<&str> = line.split('{t}').collect();",
              "            let v: i32 = f[2].parse().unwrap();",
              f'            let t = {rust}::from_i32(v).unwrap_or_else(|| panic!("sheet value {{v}} missing in enum"));',
              "            assert_eq!(t.name(), f[1]);", "            assert_eq!(t as i32, v);", "            n += 1;", "        }",
              f'        assert_eq!(n, {len(variants)}, "enum and sheet differ in size");', "    }", "}", ""]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{out}: {len(variants)} variants")


if __name__ == "__main__":
    main()
