//! The task-type definitions (port_map `ai`): what Kenshi registers for each task type at start-up
//! (F030685 TaskSystem::registerAll, 253 registrations through F039864 register), read from the
//! executable's registration code: the type, its debug name, the repertoires that offer it, its
//! score method, its preconditions (F039863, up to 11) and completion conditions (F039858), the
//! target condition (F039859) and the fields set on the definition afterwards. Conditions are
//! ids of `condition::CONDITIONS` (F039876), checked by AI slot 0 (F039867).
//!
//! Definitions are `TaskDefinition` objects of 0x178 bytes (ctor F039921); field names are their
//! offsets until the code reading them is ported (`alias` +0xc defaults to the type, `follow_up`
//! +0x10, `duration` +0x18/+0x1c = base and random range). Repertoire bits: 1 human, 2 animal,
//! 4 chained, 8 platoon, 0x10 imprisoned, 0x20 crippled (the six global TaskRepertoires,
//! F162958..F162963), 0x40 the seventh mask bit (unknown).
//!
//! Scores are AI methods (a pointer to member, F039871 calls it): the AI base class answers a
//! constant for most (vtable slots 19/43 1.0, 39 0.1, 40 0.25, 41 0.5, 42 0.8, 45 1.2, 46 1.5,
//! 47/58 2.0; F040367..F040377; slot 57 1.0, F038555), slot 48 rand * 0.4 + 0.01; the rest are AI methods by slot or
//! functions by address, ported as their tasks are.

/// How a task type is scored (F039871).
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Score {
    Const(f32),
    /// rand() * 0.4 + 0.01 (F040376).
    Random,
    /// An AI virtual method by vtable slot (not ported yet).
    Method(u8),
    /// A plain function by address (not ported yet).
    Function(u64),
}

/// The target finder stored at +0x160 (F001bfc7 calls it to fill the task's target; not ported
/// yet).
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Hook {
    Method(u8),
    Function(u64),
}

/// A task type's definition as registered.
/// @type TaskDefinition
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct TaskDef {
    pub task: u16,
    pub name: &'static str,
    pub repertoires: u8,
    pub score: Score,
    /// +0xa8/+0xac: (condition, expected, flag) that must hold to run the task; the first that
    /// fails is what stands in the way (F039870).
    pub preconditions: &'static [(u16, bool, bool)],
    /// +0x4c/+0x50: (condition, expected, flag) that together mean the task is done (F039869).
    pub done_when: &'static [(u16, bool, bool)],
    /// +0x128: (condition, expected) the target found by the hook must meet.
    pub target_condition: Option<(u16, bool)>,
    pub f04: i32,
    pub f08: u8,
    pub alias: i32,
    pub follow_up: i32,
    pub f14: u8,
    pub f15: u8,
    pub f16: u8,
    pub duration: (f32, f32),
    pub f20: u8,
    pub f21: u8,
    pub f22: u8,
    pub f23: u8,
    pub f24: f32,
    pub f28: f32,
    pub f2c: f32,
    pub f30: f32,
    pub f34: f32,
    pub f38: u8,
    pub f3c: f32,
    pub f40: u8,
    pub f41: u8,
    pub f48: u8,
    pub f120: u8,
    pub f130: i32,
    pub f134: u8,
    /// +0x160: the target finder.
    pub hook: Option<Hook>,
}

/// The definition of a task type.
pub fn def(task: u16) -> Option<&'static TaskDef> {
    DEFS.binary_search_by_key(&task, |d| d.task)
        .ok()
        .map(|i| &DEFS[i])
}

